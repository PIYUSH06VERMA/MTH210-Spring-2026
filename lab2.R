omega<-function(){
  ans<-numeric(length=5)
  temp<-numeric(length=5)
  i<-1
  while(i<=5)
  {
    u<-runif(1)
    p<-1/5
    cdf<-p
    while(u>cdf)
    {
      cdf<-cdf+p
    }
    k<-cdf*5
    flag<-TRUE
    for(j in 1:i)
    {
      if(temp[j]==k){
        flag<-FALSE
        break
      }
    }
    if(flag)
    {
      ans[k]<-i
      temp[i]<-k
      i<-i+1
    }
  }
  return(ans)
}
