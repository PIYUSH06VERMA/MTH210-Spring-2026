distn<-function()
{
  u<-runif(1)
  k<-1
  p1<-(1/3)*(1/2)^k
  p2<-(2^k)/(3^(k+1))
  cdf<-p1+p2
  while(u>cdf)
  {
    k<-k+1
    p1<-p1*(1/2)
    p2<-p2*(2/3)
    cdf<-cdf+p1+p2
  }
